# ═══════════════════════════════════════════════════════════════════════
def annotate(tool: str, name: str) -> dict:
    """שלושת השדות + סיווג, להטמעה ברשומת דוח.

    שער שאינו ברשומה מקבל `registry: "unknown"` ולא נעלם בשקט — זה בדיוק
    המצב של "נפל בין הכסאות" שהרשומה נועדה למנוע.
    """
    e = GATES.get(f"{tool}:{name}")
    if not e:
        return {"registry": "unknown",
                "protects": None, "cost_of_blocking": None, "fallback": None}
    return {"protects": e["protects"], "cost_of_blocking": e["cost_of_blocking"],
            "fallback": e["fallback"], "enforcement": e["enforcement"],
            "threshold": e["threshold"], "threshold_source": e["threshold_source"]}


def enrich(rec: dict, tool: str, name: str) -> dict:
    rec.update(annotate(tool, name))
    return rec


