def scan_source() -> dict[str, set[str]]:
    found: dict[str, set[str]] = {}
    for tool, pats in _SCAN.items():
        src = (HERE / f"{tool}.py").read_text(encoding="utf-8")
        names: set[str] = set()
        for p in pats:
            names |= set(re.findall(p, src))
        found[tool] = names
    return found


def audit(doctor_json: str | None = None) -> tuple[bool, list[str]]:
    problems: list[str] = []
    found = scan_source()
    for tool, names in found.items():
        registered = {k.split(":", 1)[1] for k in GATES if k.startswith(tool + ":")}
        for n in sorted(names - registered):
            problems.append(f"❌ {tool}:{n} — מיוצר בקוד ואינו ברשומה")
        for n in sorted(registered - names):
            if f"{tool}:{n}" in _ALIAS:
                continue
            problems.append(f"❌ {tool}:{n} — ברשומה ואינו מיוצר בקוד (שער שנעלם?)")
    if doctor_json:
        live = {c["check"] for c in json.loads(
            Path(doctor_json).read_text(encoding="utf-8"))["checks"]}
        reg = {k.split(":", 1)[1] for k in GATES if k.startswith("system_doctor:")}
        for n in sorted(live - reg):
            problems.append(f"❌ system_doctor:{n} — רץ בפועל ואינו ברשומה")
        for n in sorted(reg - live):
            problems.append(f"⚠️  system_doctor:{n} — ברשומה ולא רץ בהרצה שנבדקה")
    for k, e in GATES.items():
        for f in ("protects", "cost_of_blocking", "fallback"):
            if not e.get(f):
                problems.append(f"❌ {k} — חסר שדה {f}")
    return (not any(p.startswith("❌") for p in problems)), problems


