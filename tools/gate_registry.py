def last_failures(workdir: str | Path) -> list[dict]:
    W = Path(workdir).expanduser()
    out: list[dict] = []

    def ts(p: Path):
        try:
            return p.stat().st_mtime
        except OSError:
            return None

    qa = W / "qa_report.json"
    if qa.exists():
        d = json.loads(qa.read_text(encoding="utf-8"))
        for g in d.get("gates", []):
            if not g.get("pass"):
                out.append({"gate": f"qa_gates:{g['gate']}", "when": ts(qa),
                            "source": qa.name, "detail": g.get("detail", "")[:120],
                            "blocking": bool(g.get("hard"))})
    cn = W / "canon_report.json"
    if cn.exists():
        d = json.loads(cn.read_text(encoding="utf-8"))
        for c in d.get("checks", []):
            if c.get("level") in ("HARD_FAIL", "WARNING"):
                out.append({"gate": f"canon_lint:{c['rule']}", "when": ts(cn),
                            "source": cn.name, "detail": c.get("detail", "")[:120],
                            "blocking": c["level"] == "HARD_FAIL"})
    sq = W / "broll_sequence_report.json"
    if sq.exists():
        d = json.loads(sq.read_text(encoding="utf-8"))
        for i in d.get("issues", []):
            out.append({"gate": f"broll_sequence_qa:{i['check']}", "when": ts(sq),
                        "source": sq.name, "detail": i.get("detail", "")[:120],
                        "blocking": False})
    pf = W / "PREFLIGHT.json"
    if pf.exists():
        d = json.loads(pf.read_text(encoding="utf-8"))
        for f in d.get("findings", []):
            if f.get("severity") in ("high", "medium"):
                out.append({"gate": f"preflight:{f['check']}", "when": ts(pf),
                            "source": pf.name, "detail": str(f.get("detail", ""))[:120],
                            "blocking": False})
    cs = W / "caption_safety_report.json"
    if cs.exists():
        d = json.loads(cs.read_text(encoding="utf-8"))
        for i in d.get("fails", []) + d.get("warnings", []):
            out.append({"gate": f"caption_safety:{i.get('type')}", "when": ts(cs),
                        "source": cs.name, "detail": str(i)[:120],
                        "blocking": i in d.get("fails", [])})
    return out


